import { useEffect, useState } from 'react';
import { CopyButton } from '../../components/CopyButton';
import { Segmented } from '../../components/Segmented';
import { Button, Field, FieldGroup, Modal } from '../../components/ui';
import { FormErrors } from '../../components/FormErrors';
import { PROVIDER_TYPE_HELP, PROVIDER_TYPE_OPTIONS, TOKEN_TTL_LIMITS, MIN_SECRET_LENGTH } from './sign-in.constants';
import { formFromProvider, providerFormProblem, toProviderInput } from './sign-in.helpers';
import { useSaveProvider } from './hooks';
import type { ProviderForm, ProviderModalProps } from './sign-in.types';

/** Create or edit a sign-in provider. The type can't change once created. */
export function ProviderModal({ open, provider, onClose }: ProviderModalProps) {
  const [form, setForm] = useState<ProviderForm>(formFromProvider(provider));
  const save = useSaveProvider(provider, onClose);
  useEffect(() => {
    if (open) {
      setForm(formFromProvider(provider));
      save.reset();
    }
  }, [open, provider?.id]);

  const editing = !!provider;
  const set = (patch: Partial<ProviderForm>) => setForm((f) => ({ ...f, ...patch }));
  const problem = providerFormProblem(form, editing);
  const submit = () => !problem && save.mutate(toProviderInput(form));

  return (
    <Modal
      open={open}
      onClose={onClose}
      width={600}
      title={editing ? `Edit “${provider.name}”` : 'New sign-in provider'}
      description="Endpoints with JWT authentication use it to check the tokens your app’s users send."
      footer={
        <>
          {problem && form.name && <span className="muted small footer-note">{problem}</span>}
          <Button variant="ghost" onClick={onClose}>
            Cancel
          </Button>
          <Button variant="primary" loading={save.isPending} disabled={!!problem || save.isPending} onClick={submit}>
            {editing ? 'Save' : 'Create provider'}
          </Button>
        </>
      }
    >
      <form
        className="form-stack"
        onSubmit={(e) => {
          e.preventDefault();
          submit();
        }}
      >
        <Field label="Name" required>
          <input className="input" autoFocus placeholder="e.g. Shop customers" value={form.name} onChange={(e) => set({ name: e.target.value })} />
        </Field>
        <FieldGroup label="Who issues the tokens" help={PROVIDER_TYPE_HELP[form.type]}>
          <Segmented label="Provider type" value={form.type} options={PROVIDER_TYPE_OPTIONS} onChange={(type) => set({ type })} disabled={editing} />
        </FieldGroup>

        {form.type === 'shipflow' && editing && (
          <Field label="Issuer" help="Generated by ShipFlow; tokens carry it as iss.">
            <div className="copy-row">
              <input className="input mono" readOnly value={provider.issuer} />
              <CopyButton text={provider.issuer} iconOnly label="Copy issuer" />
            </div>
          </Field>
        )}
        {form.type !== 'shipflow' && (
          <Field label="Issuer (iss)" required help="Exactly as your identity provider writes it in tokens, e.g. https://your-tenant.auth0.com/">
            <input className="input mono" value={form.issuer} onChange={(e) => set({ issuer: e.target.value })} />
          </Field>
        )}
        {form.type === 'jwks' && (
          <Field label="JWKS URL" required help="Where the provider publishes its public keys, e.g. https://your-tenant.auth0.com/.well-known/jwks.json">
            <input className="input mono" placeholder="https://…/.well-known/jwks.json" value={form.jwksUrl} onChange={(e) => set({ jwksUrl: e.target.value })} />
          </Field>
        )}
        {form.type === 'secret' && (
          <Field
            label="Shared secret"
            required={!editing}
            help={editing ? 'Leave empty to keep the stored secret.' : `At least ${MIN_SECRET_LENGTH} characters. Stored encrypted and never shown again.`}
          >
            <input className="input mono" type="password" autoComplete="new-password" value={form.secret} onChange={(e) => set({ secret: e.target.value })} />
          </Field>
        )}
        <div className="form-grid">
          <Field label="Audience (aud)" help="Optional: only accept tokens meant for this audience.">
            <input className="input mono" value={form.audience} onChange={(e) => set({ audience: e.target.value })} />
          </Field>
          <Field label="Roles claim" help="Claim (dot path) holding the user’s roles → request.auth.roles">
            <input className="input mono" placeholder="roles" value={form.rolesClaim} onChange={(e) => set({ rolesClaim: e.target.value })} />
          </Field>
        </div>
        {form.type === 'shipflow' && (
          <Field label="Token lifetime (minutes)" help="How long tokens from the Issue token step stay valid.">
            <input
              className="input"
              type="number"
              min={TOKEN_TTL_LIMITS.min}
              max={TOKEN_TTL_LIMITS.max}
              value={form.tokenTtlMinutes}
              onChange={(e) => set({ tokenTtlMinutes: e.target.value })}
            />
          </Field>
        )}
        <FormErrors error={save.error} />
        <button type="submit" hidden aria-hidden />
      </form>
    </Modal>
  );
}
